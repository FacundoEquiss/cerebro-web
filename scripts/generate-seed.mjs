#!/usr/bin/env node
// Turns content/products.json (the demo catalogue) into SQL for the database adapters.
//
//   node scripts/generate-seed.mjs            → writes db/seed.sql in the language of config/brand.ts
//   node scripts/generate-seed.mjs --locale en
//
// Running the SQL twice is safe (it upserts). Stock already sold is NOT restored: `stock` is only
// set when the row is first inserted.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const i = process.argv.indexOf("--locale");
const brandFile = readFileSync(join(root, "config/brand.ts"), "utf8");
const locale = i > -1 ? process.argv[i + 1] : (brandFile.match(/locale:\s*"(\w+)"/)?.[1] ?? "es");
const data = JSON.parse(readFileSync(join(root, "content/products.json"), "utf8"));

const tr = (v) => (v == null ? "" : typeof v === "string" ? v : (v[locale] ?? v.es ?? v.en ?? ""));
const q = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

export function seedSql() {
  let sql = `-- Demo catalogue (${locale}). Generated by scripts/generate-seed.mjs from content/products.json.\n-- EVERYTHING HERE IS AN EXAMPLE: replace it with the real products.\n\n`;
  data.categories.forEach((c, n) => {
    sql += `insert into categories (slug, name, description, position) values (${q(c.slug)}, ${q(tr(c.name))}, ${q(tr(c.description))}, ${n})\n  on conflict (slug) do update set name = excluded.name, description = excluded.description, position = excluded.position;\n`;
  });
  for (const p of data.products) {
    const images = p.images.map(({ placeholder: _p, alt, ...rest }) => ({ ...rest, alt: tr(alt) }));
    const options = p.options.map((o) => ({ id: o.id, name: tr(o.name), values: o.values.map((v) => ({ ...v, label: tr(v.label) })) }));
    sql += `\ninsert into products (id, slug, name, description, category, price, compare_at_price, images, options, stock, featured, min_quantity, attributes, created_at)\n  values (${q(p.id)}, ${q(p.slug)}, ${q(tr(p.name))}, ${q(tr(p.description))}, ${q(p.category)}, ${p.price}, ${p.compareAtPrice ?? "null"}, ${j(images)}, ${j(options)}, ${p.stock ?? "null"}, ${p.featured}, ${p.minQuantity ?? 1}, ${j(p.attributes ?? {})}, ${q(p.createdAt)})\n  on conflict (id) do update set slug = excluded.slug, name = excluded.name, description = excluded.description, category = excluded.category,\n    price = excluded.price, compare_at_price = excluded.compare_at_price, images = excluded.images, options = excluded.options,\n    featured = excluded.featured, min_quantity = excluded.min_quantity, attributes = excluded.attributes;\n`;
    for (const v of p.variants) {
      sql += `insert into variants (id, product_id, options, stock, price) values (${q(v.id)}, ${q(p.id)}, ${j(v.options)}, ${v.stock ?? "null"}, ${v.price ?? "null"})\n  on conflict (id) do update set options = excluded.options, price = excluded.price;\n`;
    }
  }
  return sql;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, "db/seed.sql"), seedSql());
  console.log(`✓ db/seed.sql (${data.products.length} products, locale ${locale})`);
}

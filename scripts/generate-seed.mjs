#!/usr/bin/env node
// Turns content/products.json (the demo catalogue) into SQL for the database adapters.
//
//   node scripts/generate-seed.mjs            → writes db/seed.sql in the language of config/brand.ts
//   node scripts/generate-seed.mjs --locale en
//
// Running the SQL twice is safe (it upserts). Stock already sold is NOT restored: `stock` is only
// set when the row is first inserted.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const i = process.argv.indexOf("--locale");
const brandFile = readFileSync(join(root, "config/brand.ts"), "utf8");
const locale = i > -1 ? process.argv[i + 1] : (brandFile.match(/locale:\s*"(\w+)"/)?.[1] ?? "es");
const read = (file) => JSON.parse(readFileSync(file, "utf8"));

const tr = (v) => (v == null ? "" : typeof v === "string" ? v : (v[locale] ?? v.es ?? v.en ?? ""));
const q = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

/** The SQL of a catalogue file (the owner's content/products.json unless another one is given). */
export function seedSql(file = join(root, "content/products.json")) {
  const data = read(file);
  let sql = `-- Demo catalogue (${locale}). Generated by scripts/generate-seed.mjs from content/products.json.\n-- EVERYTHING HERE IS AN EXAMPLE: replace it with the real products.\n\n`;
  data.categories.forEach((c, n) => {
    sql += `insert into categories (slug, name, description, position) values (${q(c.slug)}, ${q(tr(c.name))}, ${q(tr(c.description))}, ${n})\n  on conflict (slug) do update set name = excluded.name, description = excluded.description, position = excluded.position;\n`;
  });
  for (const p of data.products) {
    const images = p.images.map(({ placeholder: _p, alt, ...rest }) => ({ ...rest, alt: tr(alt) }));
    const options = (p.options ?? []).map((o) => ({ id: o.id, name: tr(o.name), values: o.values.map((v) => ({ ...v, label: tr(v.label) })) }));
    const type = p.type ?? "physical";
    const digital = type === "digital" && p.digital ? { name: p.digital.name } : null;
    const service = type === "service" ? (p.service ?? null) : null;
    sql += `\ninsert into products (id, slug, name, description, category, price, compare_at_price, images, options, stock, featured, min_quantity, attributes, created_at, type, unit, step, max_quantity, service, digital, draft)\n  values (${q(p.id)}, ${q(p.slug)}, ${q(tr(p.name))}, ${q(tr(p.description))}, ${q(p.category)}, ${p.price ?? 0}, ${p.compareAtPrice ?? "null"}, ${j(images)}, ${j(options)}, ${p.stock ?? "null"}, ${p.featured}, ${p.minQuantity ?? 1}, ${j(p.attributes ?? {})}, ${q(p.createdAt)}, ${q(type)}, ${q(p.unit ?? "u")}, ${p.step ?? 1}, ${p.maxQuantity ?? "null"}, ${service ? j(service) : "null"}, ${digital ? j(digital) : "null"}, ${p.draft === true || (p.price == null && p.type !== "quote")})\n  on conflict (id) do update set slug = excluded.slug, name = excluded.name, description = excluded.description, category = excluded.category,\n    price = excluded.price, compare_at_price = excluded.compare_at_price, images = excluded.images, options = excluded.options,\n    featured = excluded.featured, min_quantity = excluded.min_quantity, attributes = excluded.attributes, type = excluded.type, unit = excluded.unit,\n    step = excluded.step, max_quantity = excluded.max_quantity, service = excluded.service, digital = excluded.digital, draft = excluded.draft;\n`;
    // The private file of a digital product lives in its own table (never readable with the public key).
    if (type === "digital" && p.digital?.file) {
      sql += `insert into product_files (product_id, file) values (${q(p.id)}, ${q(p.digital.file)})\n  on conflict (product_id) do update set file = excluded.file;\n`;
    }
    for (const v of p.variants ?? []) {
      sql += `insert into variants (id, product_id, options, stock, price) values (${q(v.id)}, ${q(p.id)}, ${j(v.options)}, ${v.stock ?? "null"}, ${v.price ?? "null"})\n  on conflict (id) do update set options = excluded.options, price = excluded.price;\n`;
    }
  }
  return sql;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, "db/seed.sql"), seedSql());
  console.log(`✓ db/seed.sql (${read(join(root, "content/products.json")).products.length} products, locale ${locale})`);
}
